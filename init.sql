BEGIN;

DROP TABLE IF EXISTS alocacoes, pagamentos, projetos, funcionarios, cargos, setores CASCADE;

CREATE TABLE setores (
    id            INTEGER PRIMARY KEY,
    nome          TEXT NOT NULL UNIQUE,
    centro_custo  TEXT NOT NULL UNIQUE,
    gestor_id     INTEGER  -- FK adicionada depois de criar funcionarios (referência circular)
);

CREATE TABLE cargos (
    id            INTEGER PRIMARY KEY,
    titulo        TEXT NOT NULL UNIQUE,
    setor_id      INTEGER NOT NULL REFERENCES setores(id),
    nivel         TEXT NOT NULL
                  CHECK (nivel IN ('assistente','junior','pleno','senior','gestao','diretoria')),
    salario_base  NUMERIC(12,2) NOT NULL
);

CREATE TABLE funcionarios (
    id                 INTEGER PRIMARY KEY,
    nome               TEXT NOT NULL,
    email              TEXT NOT NULL UNIQUE,
    data_nascimento    DATE NOT NULL,
    data_admissao      DATE NOT NULL,
    data_desligamento  DATE,
    cargo_id           INTEGER NOT NULL REFERENCES cargos(id),
    setor_id           INTEGER NOT NULL REFERENCES setores(id),
    gestor_id          INTEGER REFERENCES funcionarios(id),
    salario            NUMERIC(12,2) NOT NULL,
    cidade             TEXT NOT NULL,
    uf                 CHAR(2) NOT NULL,
    CHECK (data_desligamento IS NULL OR data_desligamento >= data_admissao)
);

ALTER TABLE setores
    ADD CONSTRAINT setores_gestor_fk FOREIGN KEY (gestor_id) REFERENCES funcionarios(id);

CREATE TABLE pagamentos (
    id              INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    funcionario_id  INTEGER NOT NULL REFERENCES funcionarios(id),
    competencia     DATE NOT NULL CHECK (EXTRACT(DAY FROM competencia) = 1),
    tipo            TEXT NOT NULL
                    CHECK (tipo IN ('salario','decimo_terceiro','comissao','rescisao')),
    valor_bruto     NUMERIC(12,2) NOT NULL,
    descontos       NUMERIC(12,2) NOT NULL,
    valor_liquido   NUMERIC(12,2) NOT NULL,
    data_pagamento  DATE NOT NULL
);

CREATE TABLE projetos (
    id           INTEGER PRIMARY KEY,
    nome         TEXT NOT NULL UNIQUE,
    setor_id     INTEGER NOT NULL REFERENCES setores(id),
    orcamento    NUMERIC(14,2) NOT NULL,
    data_inicio  DATE NOT NULL,
    data_fim     DATE,
    status       TEXT NOT NULL CHECK (status IN ('planejado','em_andamento','concluido'))
);

CREATE TABLE alocacoes (
    funcionario_id  INTEGER NOT NULL REFERENCES funcionarios(id),
    projeto_id      INTEGER NOT NULL REFERENCES projetos(id),
    papel           TEXT NOT NULL,
    horas_semanais  INTEGER NOT NULL CHECK (horas_semanais BETWEEN 1 AND 44),
    PRIMARY KEY (funcionario_id, projeto_id)
);

CREATE INDEX idx_pagamentos_funcionario ON pagamentos (funcionario_id);
CREATE INDEX idx_pagamentos_competencia ON pagamentos (competencia);
CREATE INDEX idx_funcionarios_setor ON funcionarios (setor_id);

COMMENT ON TABLE setores IS 'Departamentos da empresa Nexo Soluções.';
COMMENT ON COLUMN setores.gestor_id IS 'Funcionário que gerencia o setor.';

COMMENT ON TABLE cargos IS 'Cargos existentes, cada um pertencente a um setor.';
COMMENT ON COLUMN cargos.salario_base IS 'Salário de referência do cargo, em reais.';

COMMENT ON TABLE funcionarios IS 'Todos os funcionários, ativos e desligados.';
COMMENT ON COLUMN funcionarios.data_desligamento IS 'NULL significa funcionário ativo.';
COMMENT ON COLUMN funcionarios.gestor_id IS 'Chefe direto. NULL apenas para a diretora executiva.';
COMMENT ON COLUMN funcionarios.salario IS 'Salário mensal ATUAL em reais, já com o reajuste de 5% de março/2026.';
COMMENT ON COLUMN funcionarios.setor_id IS 'Setor do funcionário (igual a cargos.setor_id do seu cargo).';

COMMENT ON TABLE pagamentos IS 'Folha de pagamento de out/2025 a set/2026. Um funcionário pode ter vários pagamentos por mês (um por tipo).';
COMMENT ON COLUMN pagamentos.competencia IS 'Mês de referência, sempre o dia 1 (ex.: 2026-03-01 = março/2026).';
COMMENT ON COLUMN pagamentos.tipo IS 'salario, decimo_terceiro, comissao (só vendas) ou rescisao (desligados).';
COMMENT ON COLUMN pagamentos.valor_liquido IS 'valor_bruto - descontos, em reais.';

COMMENT ON TABLE projetos IS 'Projetos internos, cada um pertencente a um setor.';
COMMENT ON COLUMN projetos.data_fim IS 'NULL significa sem data de término definida.';

COMMENT ON TABLE alocacoes IS 'Quais funcionários trabalham em quais projetos (N:N).';

